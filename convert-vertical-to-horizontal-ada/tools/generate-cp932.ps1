# Regenerate only on Windows. Production Linux needs neither Windows nor iconv.
$ErrorActionPreference = 'Stop'
Add-Type -TypeDefinition @'
using System;
using System.Collections.Generic;
using System.Runtime.InteropServices;
using System.Text;
public static class EpubCP932Tables {
    [DllImport("kernel32.dll", CharSet=CharSet.Unicode, ExactSpelling=true)]
    static extern int MultiByteToWideChar(uint page, uint flags, byte[] input,
        int length, [Out] char[] output, int capacity);
    [DllImport("kernel32.dll", CharSet=CharSet.Unicode, ExactSpelling=true)]
    static extern int WideCharToMultiByte(uint page, uint flags, char[] input,
        int length, [Out] byte[] output, int capacity, IntPtr replacement,
        out int substituted);
    static void Emit(StringBuilder text, string name, SortedDictionary<int,int> map) {
        text.Append("   " + name + " : constant Mapping := [\n");
        foreach (var item in map)
            text.AppendFormat("      16#{0:X4}# => 16#{1:X4}#,\n",item.Key,item.Value);
        text.Append("      others => Invalid];\n");
    }
    public static string Generate() {
        var decode = new SortedDictionary<int,int>();
        var encode = new SortedDictionary<int,int>();
        var chars = new char[2]; var bytes = new byte[4];
        for (int value=0;value<=65535;value++) {
            if (value>255) {
                int lead=value>>8, trail=value&255;
                if (!((lead>=0x81 && lead<=0x9f)||(lead>=0xe0 && lead<=0xfc)) ||
                    trail<0x40 || trail>0xfc || trail==0x7f) continue;
                bytes[0]=(byte)lead;bytes[1]=(byte)trail;
            } else bytes[0]=(byte)value;
            if (MultiByteToWideChar(932,8,bytes,value>255?2:1,chars,2)==1)
                decode.Add(value,chars[0]);
        }
        for (int value=0;value<=65535;value++) {
            if (value>=0xd800 && value<=0xdfff) continue;
            chars[0]=(char)value; int substituted;
            int length=WideCharToMultiByte(932,0x400,chars,1,bytes,4,IntPtr.Zero,out substituted);
            if (substituted==0 && (length==1 || length==2))
                encode.Add(value,length==1?bytes[0]:(bytes[0]<<8)|bytes[1]);
        }
        var text=new StringBuilder();
        text.Append("--  Generated by tools/generate-cp932.ps1 from strict Windows CP932 APIs.\n");
        text.Append("--  Includes canonical encoding choices and Windows private-use mappings.\n");
        text.Append("with Interfaces;\npackage Epub.CP932_Tables with Pure is\n");
        text.Append("   Invalid : constant := 16#FFFF#;\n");
        text.Append("   type Mapping is array (Natural range 0 .. 65535) of Interfaces.Unsigned_16;\n");
        Emit(text,"Decoding",decode); Emit(text,"Encoding",encode);
        text.Append("end Epub.CP932_Tables;\n");return text.ToString();
    }
}
'@
$destination = Join-Path $PSScriptRoot '../src/epub-cp932_tables.ads'
[IO.File]::WriteAllText([IO.Path]::GetFullPath($destination), [EpubCP932Tables]::Generate(), [Text.UTF8Encoding]::new($false))
